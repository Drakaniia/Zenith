// Generates src/lib/profile-avatars.ts: the emoji offered as profile pictures, taken from
// Microsoft's Fluent Emoji (flat style, MIT licence) through @iconify-json/fluent-emoji-flat.
// Only the curated icons below are copied, so the app doesn't ship the whole set.
//
//   node scripts/gen-profile-avatars.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const PICKS = [
  "bust-in-silhouette", "boy", "girl", "alien", "robot", "ghost",
  "cat-face", "dog-face", "fox", "bear", "panda", "tiger-face", "lion", "owl", "penguin", "frog", "unicorn", "octopus",
  "strawberry", "leaf-fluttering-in-wind", "tangerine", "avocado", "cherries", "watermelon", "pizza", "doughnut",
  "blossom", "cherry-blossom", "sunflower", "four-leaf-clover", "cactus", "palm-tree",
  "camera", "videocassette", "video-game", "soccer-ball", "basketball", "musical-note", "guitar", "headphone",
  "high-voltage", "fire", "balloon", "automobile", "rocket", "sun-behind-cloud", "rainbow", "crescent-moon",
  "star", "sparkles", "gem-stone", "crown", "light-bulb", "artist-palette", "books", "laptop", "briefcase", "house",
];

const root = fileURLToPath(new URL("..", import.meta.url));
const set = JSON.parse(readFileSync(`${root}node_modules/@iconify-json/fluent-emoji-flat/icons.json`, "utf8"));

const label = (id) => id.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase());
const entries = PICKS.map((id) => {
  const icon = set.icons[id];
  if (!icon) throw new Error(`fluent-emoji-flat has no icon "${id}"`);
  const w = icon.width ?? set.width ?? 16;
  const h = icon.height ?? set.height ?? 16;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.left ?? 0} ${icon.top ?? 0} ${w} ${h}">${icon.body}</svg>`;
  return `  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(label(id))}, svg: ${JSON.stringify(svg)} },`;
});

const out = `// Generated by scripts/gen-profile-avatars.mjs; do not edit.
// Fluent Emoji (flat) by Microsoft, MIT licence: https://github.com/microsoft/fluentui-emoji

export interface ProfileEmoji {
  id: string;
  label: string;
  svg: string;
}

export const PROFILE_EMOJI: ProfileEmoji[] = [
${entries.join("\n")}
];
`;
writeFileSync(`${root}src/lib/profile-avatars.ts`, out);
console.log(`Wrote ${PICKS.length} emoji to src/lib/profile-avatars.ts`);
